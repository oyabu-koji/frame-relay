"""Real I/O observation of the unchanged legacy Range implementation.

Loaded only after the S20 guard. Wrappers call the original hash/parser/iterator
and return their actual results. Generated bytes are not playable media or Log.
"""
import hashlib
import json
import sqlite3
import threading
import time
import weakref
from pathlib import Path


def run(runtime):
    from fastapi.testclient import TestClient
    from app.core.settings import load_settings
    from app.db.connection import connect
    from app.main import app
    from app.repositories.derived_files import insert_derived_file
    from app.repositories.processed_results import (
        clear_active_processed_result, insert_ready_processed_result, set_active_processed_result,
    )
    from app.services import processed_result_integrity as integrity
    from app.services import processed_result_stream as stream
    from tests.test_processed_result_streaming_api import _create_deliverable

    settings = load_settings()
    payload = bytes(range(256)) * 8192 + b"S20-range-tail017"
    assert len(payload) == 2 * 1024 * 1024 + 17
    replacement = bytes(reversed(range(256))) * 8192 + b"S20-range-tailv02"
    assert len(replacement) == len(payload)
    report = {"kind": "unchanged legacy server Range I/O probe", "payload_bytes": len(payload),
        "requested_bytes": 1024, "payload_sha256": hashlib.sha256(payload).hexdigest(),
        "hash_calls": [], "descriptors": [], "writer": {}, "requests": {}, "passed": False,
        "interpretation": "synthetic bytes only; not playback, conversion, product distribution or ACK evidence"}
    active = {"stage": "setup", "request_hash_index": 0}
    local = threading.local()
    second_hash_read = threading.Event()
    release_second_hash = threading.Event()
    original_hash = integrity.hash_file_sha256
    original_open = Path.open
    original_connect = stream.connect
    original_iterator = stream.iter_open_file
    original_parser = stream.parse_range_header
    descriptors = []
    pending = None
    thread_failure = []
    response_holder = []

    def candidate(conn, asset, ordinal):
        result_id = f"{ordinal:x}" * 32
        path = settings.media_root / f"previews/{result_id}.mp4"
        path.write_bytes(replacement)
        derived = insert_derived_file(conn, asset_id=asset["id"], kind="preview",
            path=f"previews/{result_id}.mp4", mime_type="video/mp4", size_bytes=len(replacement))
        result, _created = insert_ready_processed_result(conn, asset_id=asset["id"], derived_file_id=derived["id"],
            mime_type="video/mp4", size_bytes=len(replacement), sha256=hashlib.sha256(replacement).hexdigest(), result_id=result_id)
        return result

    def switch(asset, target):
        connection = connect(settings.database_path, 5000)
        try:
            with connection:
                clear_active_processed_result(connection, asset_id=asset["id"])
                set_active_processed_result(connection, asset_id=asset["id"], result_id=target["id"])
        finally:
            connection.close()

    class CountingReader:
        def __init__(self, actual, observation):
            self.actual = actual
            self.observation = observation

        def __enter__(self):
            self.actual.__enter__()
            return self

        def __exit__(self, *args):
            result = self.actual.__exit__(*args)
            self.observation["hash_descriptor_closed"] = self.actual.closed
            return result

        def read(self, length=-1):
            block = self.actual.read(length)
            self.observation["read_sizes"].append(len(block))
            self.observation["bytes_read"] += len(block)
            # Synchronize during the real second hash, after its first actual
            # read, while the original connection's BEGIN IMMEDIATE is active.
            if (self.observation["stage"] == "short-range" and self.observation["index_in_request"] == 2
                    and len(self.observation["read_sizes"]) == 1):
                second_hash_read.set()
                if not release_second_hash.wait(10):
                    raise TimeoutError("Contender did not release the second-hash observation")
            return block

    def observed_open(path, *args, **kwargs):
        actual = original_open(path, *args, **kwargs)
        observation = getattr(local, "hash_observation", None)
        if observation is not None and str(path.resolve()) == observation["path"]:
            return CountingReader(actual, observation)
        return actual

    def observed_connect(*args, **kwargs):
        connection = original_connect(*args, **kwargs)
        local.connection = weakref.ref(connection)
        return connection

    def observed_hash(path, *, block_size=integrity.HASH_BLOCK_SIZE_BYTES):
        active["request_hash_index"] += 1
        observation = {"stage": active["stage"], "index_in_request": active["request_hash_index"],
            "path": str(path.resolve()), "block_size": block_size, "bytes_read": 0, "read_sizes": [],
            "connection_in_transaction": bool(local.connection().in_transaction),
            "hash_descriptor_closed": False}
        report["hash_calls"].append(observation)
        local.hash_observation = observation
        try:
            value = original_hash(path, block_size=block_size)
            observation["actual_digest"] = value
            return value
        finally:
            local.hash_observation = None

    def observed_iterator(file, *, start, end):
        observation = {"stage": active["stage"], "start": start, "end": end,
            "fd": file.fileno(), "closed_at_acceptance": file.closed}
        descriptors.append((file, observation))
        report["descriptors"].append(observation)
        if active["stage"] == "switch-after-descriptor":
            switch(first_asset, second_result)
            observation["pointer_switched_before_first_body_read"] = True
        return original_iterator(file, start=start, end=end)

    def observed_parser(header, total_size):
        parsed = original_parser(header, total_size)
        if active["stage"] == "switch-before-descriptor":
            switch(other_asset, other_new_result)
        return parsed

    def begin(stage):
        active["stage"] = stage
        active["request_hash_index"] = 0

    def request(client, asset, result, *, byte_range=None):
        headers = {"Authorization": "Bearer " + settings.api_token}
        if byte_range:
            headers["Range"] = byte_range
        return client.get(f"/assets/{asset['id']}/results/{result['id']}", headers=headers)

    try:
        with TestClient(app) as client:
            connection = connect(settings.database_path, 5000)
            try:
                with connection:
                    first_asset, first_result, _derived, _path = _create_deliverable(
                        connection, settings.media_root, ordinal=1, content=payload)
                    second_result = candidate(connection, first_asset, 2)
                    other_asset, other_result, _derived, _path = _create_deliverable(
                        connection, settings.media_root, ordinal=3, content=payload)
                    other_new_result = candidate(connection, other_asset, 4)
            finally:
                connection.close()

            Path.open = observed_open
            integrity.hash_file_sha256 = observed_hash
            stream.connect = observed_connect
            stream.iter_open_file = observed_iterator
            stream.parse_range_header = observed_parser
            contender = sqlite3.connect(settings.database_path, timeout=0.025)
            contender.execute("PRAGMA busy_timeout=25")
            begin("short-range")

            def fetch_short():
                try:
                    response_holder.append(request(client, first_asset, first_result, byte_range="bytes=0-1023"))
                except BaseException as error:
                    thread_failure.append({"type": type(error).__name__, "message": str(error)})

            pending = threading.Thread(target=fetch_short, name="S20-short-range", daemon=True)
            pending.start()
            try:
                if not second_hash_read.wait(10):
                    raise TimeoutError("Second real hash read was not observed")
                started = time.perf_counter()
                try:
                    contender.execute("BEGIN IMMEDIATE")
                    report["writer"] = {"blocked": False, "elapsed_seconds": time.perf_counter() - started}
                    contender.rollback()
                except sqlite3.OperationalError as error:
                    report["writer"] = {"blocked": True, "sqlite_errorcode": error.sqlite_errorcode,
                        "sqlite_errorname": error.sqlite_errorname, "message": str(error),
                        "elapsed_seconds": time.perf_counter() - started}
            finally:
                release_second_hash.set()
                contender.close()
                pending.join(timeout=10)
            assert not pending.is_alive(), "Range request did not actually terminate"
            assert not thread_failure, thread_failure
            response = response_holder[0]
            report["requests"]["short-range"] = {"status": response.status_code, "body_bytes": len(response.content),
                "content_range": response.headers.get("content-range"), "body_matches": response.content == payload[:1024]}
            measured = [item for item in report["hash_calls"] if item["stage"] == "short-range"]
            assert response.status_code == 206 and response.content == payload[:1024]
            assert len(measured) == 2 and [item["bytes_read"] for item in measured] == [len(payload), len(payload)]
            assert [item["connection_in_transaction"] for item in measured] == [False, True]
            assert all(item["hash_descriptor_closed"] for item in measured)
            assert report["writer"].get("sqlite_errorcode") == sqlite3.SQLITE_BUSY

            begin("switch-after-descriptor")
            accepted = request(client, first_asset, first_result)
            report["requests"]["accepted-v1"] = {"status": accepted.status_code, "bytes": len(accepted.content),
                "result_id": accepted.headers.get("x-processed-result-id"),
                "matches_v1_after_pointer_switch": accepted.content == payload}
            assert accepted.status_code == 200 and accepted.content == payload
            assert accepted.headers["x-processed-result-id"] == first_result["id"]
            begin("late-new-v1-request")
            stale = request(client, first_asset, first_result, byte_range="bytes=0-1023")
            report["requests"]["late-v1"] = {"status": stale.status_code, "body": stale.json()}
            assert stale.status_code == 409 and stale.json()["code"] == "processed_result_superseded"
            begin("new-v2-request")
            current = request(client, first_asset, second_result, byte_range="bytes=0-1023")
            report["requests"]["current-v2"] = {"status": current.status_code,
                "body_bytes": len(current.content), "matches_v2": current.content == replacement[:1024]}
            assert current.status_code == 206 and current.content == replacement[:1024]

            begin("switch-before-descriptor")
            before_count = len(descriptors)
            superseded = request(client, other_asset, other_result, byte_range="bytes=0-1023")
            report["requests"]["switch-before-descriptor"] = {"status": superseded.status_code,
                "body": superseded.json(), "accepted_descriptor_count": len(descriptors) - before_count}
            assert superseded.status_code == 409 and superseded.json()["code"] == "processed_result_superseded"
            assert len(descriptors) == before_count
            for file, observation in descriptors:
                observation["closed_after_body_completion"] = file.closed
            assert all(file.closed for file, _observation in descriptors)
            report["passed"] = True
    finally:
        release_second_hash.set()
        if pending is not None and pending.is_alive():
            pending.join(timeout=10)
        Path.open = original_open
        integrity.hash_file_sha256 = original_hash
        stream.connect = original_connect
        stream.iter_open_file = original_iterator
        stream.parse_range_header = original_parser
        report["request_thread_terminated"] = pending is None or not pending.is_alive()
        report["request_thread_errors"] = thread_failure
        for file, observation in descriptors:
            observation["closed_at_probe_end"] = file.closed
            if not file.closed:
                # Report the real failure first; cleanup is not evidence that the
                # response/iterator itself completed or released its descriptor.
                file.close()
                observation["emergency_cleanup_close"] = True
        with (runtime / "range-probe-results.json").open("x") as output:
            json.dump(report, output, indent=2, sort_keys=True)
            output.write("\n")
    return report
